  const escapeHtml = (val) => String(val ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

  const renderCard = (movie, upcoming = false) => {
    const link = `movies.html?movie=${encodeURIComponent(movie.id)}#${upcoming ? 'upcoming-title' : 'browse'}`;
    const poster = movie.poster
      ? `<img class="real-movie-poster" src="${escapeHtml(movie.poster)}" alt="${escapeHtml(movie.title)}" loading="lazy">`
      : `<span class="movie-poster-fallback">${escapeHtml(movie.title)}</span>`;

    const cta = upcoming
      ? `<button class="movie-link-label prebook-btn" type="button" data-movie-id="${escapeHtml(movie.id)}" data-movie-title="${escapeHtml(movie.title)}">Pre-book on CineBuzz <span>★</span></button>`
      : `<a class="movie-link-label" href="${link}">Find showtimes <span>→</span></a>`;

    return `
      <article class="real-movie-card" data-movie-id="${escapeHtml(movie.id)}">
        <a class="real-movie-poster-link" href="${link}" aria-label="${escapeHtml(movie.title)}">${poster}</a>
        <div class="real-movie-copy">
          <span class="movie-card-meta">${escapeHtml([movie.language, (movie.genres || []).slice(0, 2).join(' · '), movie.certificate].filter(Boolean).join(' · '))}</span>
          <h3>${escapeHtml(movie.title)}</h3>
          <p>${escapeHtml(movie.description)}</p>
          <span class="movie-runtime">${escapeHtml(movie.releaseDate)}</span>
        </div>
        ${cta}
      </article>
    `;
  };

  function initCatalog() {
    const homeNow = document.querySelector('#home-now-showing');
    const homeUpcoming = document.querySelector('#home-upcoming');
    const moviesNow = document.querySelector('#real-movie-grid');
    const moviesUpcoming = document.querySelector('#upcoming-movie-grid');

    const nowShowingMovies = window.CINEBUZZ_MOVIES.filter((m) => m.status === 'now-showing');
    const upcomingMovies = window.CINEBUZZ_MOVIES.filter((m) => m.status === 'upcoming');

    if (homeNow) homeNow.innerHTML = nowShowingMovies.map((m) => renderCard(m)).join('');
    if (homeUpcoming) homeUpcoming.innerHTML = upcomingMovies.map((m) => renderCard(m, true)).join('');
    if (moviesNow) moviesNow.innerHTML = nowShowingMovies.map((m) => renderCard(m)).join('');
    if (moviesUpcoming) moviesUpcoming.innerHTML = upcomingMovies.map((m) => renderCard(m, true)).join('');

    // Pre-book button handling
    document.querySelectorAll('.prebook-btn').forEach((btn) => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        const id = btn.dataset.movieId;
        const title = btn.dataset.movieTitle;
        try {
          const prebooks = JSON.parse(localStorage.getItem('cinebuzz_prebooks') || '[]');
          if (!prebooks.includes(id)) {
            prebooks.push(id);
            localStorage.setItem('cinebuzz_prebooks', JSON.stringify(prebooks));
          }
          const feedback = document.querySelector('#prebook-feedback');
          if (feedback) {
            feedback.textContent = `✓ Pre-booking interest saved for "${title}". We'll notify this browser when tickets drop!`;
            feedback.style.color = 'var(--green)';
          } else {
            alert(`✓ Pre-booking interest saved for "${title}"!`);
          }
          btn.textContent = 'Pre-booked ✓';
          btn.disabled = true;
        } catch {
          alert(`Pre-booking interest recorded for "${title}".`);
        }
      });
    });

    // Poster fallback error handlers
    document.querySelectorAll('.real-movie-poster').forEach((img) => {
      img.addEventListener('error', () => {
        const fallback = document.createElement('span');
        fallback.className = 'movie-poster-fallback';
        fallback.textContent = img.alt;
        img.replaceWith(fallback);
      }, { once: true });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initCatalog);
  } else {
    initCatalog();
  }
